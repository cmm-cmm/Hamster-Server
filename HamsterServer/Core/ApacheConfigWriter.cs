using System.Security.Cryptography;
using System.Text;
using HamsterServer.Models;

namespace HamsterServer.Core;

public class ApacheConfigWriter
{
    private const string PhpIniGeneratedHeader = "; PHP FastCGI Configuration — Generated by Hamster Server";
    private const string PhpIniSchemaMarker = "; Hamster Server php.ini schema: 2";
    private const string LegacyPhpIniGeneratedHeader = "; PHP FastCGI Configuration — Generated by XServer";

    private readonly string _rootDir;
    private readonly AppConfig _config;

    public ApacheConfigWriter(string rootDir, AppConfig config)
    {
        _rootDir = rootDir;
        _config = config;
    }

    private static string P(string path) => path.Replace('\\', '/');

    private string VirtualHostAddress => _config.Apache.AllowLanAccess ? "*" : "127.0.0.1";

    // mod_proxy_fcgi opens a fresh TCP connection per request by default, which costs ~0.3 ms
    // each and piles up TIME_WAIT sockets until the ephemeral port range runs dry. Pooling fixes
    // both, but `max` is load-bearing: it defaults to ThreadsPerChild, so Apache would hold far
    // more backend connections than php-cgi has children, and requests handed a connection no
    // child is serving die on AH01075 polling timeouts. Measured at 32-way concurrency, reuse
    // without `max` dropped from 13 066 to 13 req/s; with `max` it holds ~18 000. `ttl` discards
    // connections that an exiting child left half-closed.
    private string FcgiReuse => $"enablereuse=on max={_config.Php.Workers} ttl=15";

    private string Listen(int port, bool ssl = false)
    {
        var endpoint = _config.Apache.AllowLanAccess ? port.ToString() : $"127.0.0.1:{port}";
        return ssl ? $"Listen {endpoint} https" : $"Listen {endpoint}";
    }

    public static bool IsValidServerName(string value)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Any(char.IsWhiteSpace)) return false;
        var host = value.StartsWith("*.", StringComparison.Ordinal) ? $"wildcard.{value[2..]}" : value;
        return host.Equals("localhost", StringComparison.OrdinalIgnoreCase) ||
               Uri.CheckHostName(host) == UriHostNameType.Dns;
    }

    public static bool AreValidServerAliases(string value) =>
        string.IsNullOrWhiteSpace(value) ||
        value.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries).All(IsValidServerName);

    // ─── httpd.conf ──────────────────────────────────────────────────────────

    public void WriteHttpdConf(string outputPath, string apacheDir, string wwwDir, string configDir)
    {
        ValidateConfiguration();
        var logsDir = Path.Combine(configDir, "logs");
        Directory.CreateDirectory(logsDir);
        Directory.CreateDirectory(Path.Combine(configDir, "vhosts"));

        bool isProd = _config.ServerMode == ServerMode.Production;
        // 300s dev timeout lets hung PHP scripts block Apache threads for 5 minutes.
        // 60s is generous for any legitimate dev operation and matches production.
        int timeout = 60;
        bool sslReady = _config.Apache.EnableSsl &&
                        !string.IsNullOrWhiteSpace(_config.Apache.SslCertFile) &&
                        !string.IsNullOrWhiteSpace(_config.Apache.SslKeyFile);

        var sb = new StringBuilder();
        sb.AppendLine("# Hamster Server - Apache HTTP Server Configuration");
        sb.AppendLine("# Auto-generated — do not edit manually");
        sb.AppendLine($"# Mode: {_config.ServerMode}");
        sb.AppendLine();
        sb.AppendLine($"ServerRoot \"{P(apacheDir)}\"");
        sb.AppendLine($"ServerName {_config.Apache.ServerName}");
        sb.AppendLine("ServerAdmin webmaster@localhost");
        sb.AppendLine("ServerTokens Prod");
        sb.AppendLine("ServerSignature Off");
        sb.AppendLine();
        sb.AppendLine(Listen(_config.Apache.Port));
        foreach (var ep in _config.Apache.ExtraPorts.Where(p => p.Enabled))
            sb.AppendLine(Listen(ep.Port, ep.IsSsl));
        if (sslReady)
            sb.AppendLine(Listen(_config.Apache.SslPort, ssl: true));
        sb.AppendLine();
        sb.AppendLine($"PidFile \"{P(configDir)}/apache.pid\"");
        sb.AppendLine($"ErrorLog \"{P(logsDir)}/error.log\"");
        sb.AppendLine($"LogLevel {(isProd ? "error" : "info")}");
        sb.AppendLine();

        // ── Modules ────────────────────────────────────────────────────────
        sb.AppendLine("# Modules");
        string[] modules =
        [
            "actions", "alias", "allowmethods",
            "auth_basic", "authn_core", "authn_file",
            "authz_core", "authz_groupfile", "authz_host", "authz_user",
            "autoindex", "dir", "env", "filter",
            "headers", "log_config", "mime", "negotiation",
            "proxy", "proxy_fcgi",
            "rewrite", "setenvif",
            "slotmem_shm", "socache_shmcb",
            "status", "version"
        ];
        foreach (var m in modules)
            sb.AppendLine($"LoadModule {m}_module modules/mod_{m}.so");

        if (_config.Apache.EnableGzip)
            sb.AppendLine("LoadModule deflate_module modules/mod_deflate.so");
        if (_config.Apache.EnableCache)
            sb.AppendLine("LoadModule expires_module modules/mod_expires.so");
        bool brotliDllExists = File.Exists(Path.Combine(apacheDir, "modules", "mod_brotli.so"));
        if (_config.Apache.EnableBrotli && brotliDllExists)
            sb.AppendLine("LoadModule brotli_module modules/mod_brotli.so");
        // Fix 4.4: mod_http2 — chỉ load khi SSL bật VÀ DLL tồn tại (HTTP/2 = HTTPS only)
        bool http2Available = false;
        if (sslReady)
        {
            sb.AppendLine("LoadModule ssl_module modules/mod_ssl.so");
            http2Available = File.Exists(Path.Combine(apacheDir, "modules", "mod_http2.so"));
            if (http2Available)
                sb.AppendLine("LoadModule http2_module modules/mod_http2.so");
        }
        if (_config.VHosts.Any(v => v.Enabled && FrameworkProfiles.Get(v.Framework).IsReverseProxy))
        {
            sb.AppendLine("LoadModule proxy_http_module modules/mod_proxy_http.so");
            sb.AppendLine("LoadModule proxy_wstunnel_module modules/mod_proxy_wstunnel.so");
        }
        if (isProd && File.Exists(Path.Combine(apacheDir, "modules", "mod_reqtimeout.so")))
            sb.AppendLine("LoadModule reqtimeout_module modules/mod_reqtimeout.so");

        sb.AppendLine();

        // ── MIME / Logging ─────────────────────────────────────────────────
        sb.AppendLine($"TypesConfig \"{P(apacheDir)}/conf/mime.types\"");
        sb.AppendLine("AddType application/x-httpd-php .php");
        sb.AppendLine();
        sb.AppendLine("LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b \\\"%{Referer}i\\\" \\\"%{User-Agent}i\\\"\" combined");
        sb.AppendLine($"CustomLog \"{P(logsDir)}/access.log\" combined");
        sb.AppendLine();

        // ── Default settings ───────────────────────────────────────────────
        sb.AppendLine("DirectoryIndex index.php index.html index.htm");
        sb.AppendLine();

        // ── Performance ────────────────────────────────────────────────────
        sb.AppendLine("# Performance");
        sb.AppendLine("KeepAlive On");
        sb.AppendLine($"MaxKeepAliveRequests {(isProd ? 1000 : 200)}");
        sb.AppendLine($"KeepAliveTimeout {_config.Apache.KeepAliveTimeout}");
        sb.AppendLine($"Timeout {timeout}");
        sb.AppendLine($"ProxyTimeout {timeout}");
        sb.AppendLine();
        sb.AppendLine("# Windows: disable kernel-level I/O features not supported on Windows");
        sb.AppendLine("EnableSendfile Off");
        sb.AppendLine("EnableMMAP Off");
        sb.AppendLine();
        sb.AppendLine("<IfModule mpm_winnt_module>");
        sb.AppendLine($"    ThreadsPerChild        {_config.Apache.MaxClients}");
        // mpm_winnt runs a single child, so recycling it cycles the whole server. In development
        // 5000 connections is roughly an hour of asset-heavy page loads, and each recycle showed
        // up as a stall or a dropped connection — leave the child alone (0) and keep recycling
        // for production, where a long-lived process is the thing worth guarding against.
        sb.AppendLine($"    MaxConnectionsPerChild {(isProd ? 10000 : 0)}");
        // GracefulShutdownTimeout không tồn tại trong mpm_winnt (chỉ có trên Unix prefork/worker/event)
        sb.AppendLine("</IfModule>");
        sb.AppendLine();

        // ── Security ───────────────────────────────────────────────────────
        sb.AppendLine("# Security");
        sb.AppendLine("<IfModule mod_headers.c>");
        sb.AppendLine("    Header always set X-Content-Type-Options \"nosniff\"");
        sb.AppendLine("    Header always set X-Frame-Options \"SAMEORIGIN\"");
        sb.AppendLine("    Header always set X-XSS-Protection \"1; mode=block\"");
        // Fix 3.2: modern security headers — browser warnings + CSRF mitigation
        sb.AppendLine("    Header always set Referrer-Policy \"strict-origin-when-cross-origin\"");
        sb.AppendLine("    Header always set Permissions-Policy \"geolocation=(), microphone=(), camera=()\"");
        sb.AppendLine("</IfModule>");
        sb.AppendLine("<Files \".ht*\">");
        sb.AppendLine("    Require all denied");
        sb.AppendLine("</Files>");
        // Fix 3.1: request size limits — tránh header bomb / URL flood
        sb.AppendLine("LimitRequestBody     104857600");  // 100 MB max body
        sb.AppendLine("LimitRequestFields   100");        // max 100 HTTP headers per request
        sb.AppendLine("LimitRequestFieldSize 8190");      // max header field size (bytes)
        sb.AppendLine("LimitRequestLine     8190");       // max URL length
        sb.AppendLine();

        if (isProd)
        {
            sb.AppendLine("# Slow HTTP attack mitigation (Production)");
            sb.AppendLine("<IfModule mod_reqtimeout.c>");
            sb.AppendLine("    RequestReadTimeout header=20-40,minrate=500 body=20,minrate=500");
            sb.AppendLine("</IfModule>");
            sb.AppendLine();
        }

        // ── Document Root ──────────────────────────────────────────────────
        sb.AppendLine($"DocumentRoot \"{P(wwwDir)}\"");
        sb.AppendLine($"<Directory \"{P(wwwDir)}\">");
        sb.AppendLine($"    Options {(isProd ? "FollowSymLinks" : "Indexes FollowSymLinks")}");
        sb.AppendLine("    AllowOverride All");
        sb.AppendLine("    Require all granted");
        sb.AppendLine("</Directory>");
        sb.AppendLine();

        // ── PHP via FastCGI ── configured per-VirtualHost so that DOCUMENT_ROOT resolves
        // to the VHost's own docroot when ProxyFCGISetEnvIf reads the PHP_FCGI_SCRIPT env var.
        // Global ProxyPassMatch + ProxyFCGISetEnvIf does NOT see env vars set inside a VHost's
        // RewriteRule, causing "No input file specified" for non-default VHosts.
        sb.AppendLine("# PHP FastCGI: configured per-VirtualHost (see config/vhosts/*.conf)");
        sb.AppendLine();

        // ── Gzip ───────────────────────────────────────────────────────────
        if (_config.Apache.EnableGzip)
        {
            sb.AppendLine("# Gzip Compression");
            sb.AppendLine("<IfModule mod_deflate.c>");
            sb.AppendLine("    AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css");
            sb.AppendLine("    AddOutputFilterByType DEFLATE text/javascript application/javascript application/json");
            sb.AppendLine("    AddOutputFilterByType DEFLATE application/x-javascript application/xhtml+xml");
            sb.AppendLine("    BrowserMatch ^Mozilla/4 gzip-only-text/html");
            sb.AppendLine("    BrowserMatch ^Mozilla/4\\.0[678] no-gzip");
            sb.AppendLine("    BrowserMatch \\bMSIE !no-gzip !gzip-only-text/html");
            sb.AppendLine("</IfModule>");
            sb.AppendLine();
        }

        // ── Brotli (Fix 3.1) — 15-25% tốt hơn gzip, chỉ kích hoạt khi có mod_brotli.so ──
        if (_config.Apache.EnableBrotli && brotliDllExists)
        {
            sb.AppendLine("# Brotli Compression (mod_brotli)");
            sb.AppendLine("<IfModule mod_brotli.c>");
            sb.AppendLine("    BrotliCompressionQuality 6");
            sb.AppendLine("    AddOutputFilterByType BROTLI_COMPRESS text/html text/plain text/xml text/css");
            sb.AppendLine("    AddOutputFilterByType BROTLI_COMPRESS text/javascript application/javascript application/json");
            sb.AppendLine("    AddOutputFilterByType BROTLI_COMPRESS application/x-javascript application/xhtml+xml");
            sb.AppendLine("    AddOutputFilterByType BROTLI_COMPRESS image/svg+xml application/font-woff2");
            sb.AppendLine("</IfModule>");
            sb.AppendLine();
        }

        // ── Browser Cache ──────────────────────────────────────────────────
        if (_config.Apache.EnableCache)
        {
            sb.AppendLine("# Browser Caching");
            sb.AppendLine("<IfModule mod_expires.c>");
            sb.AppendLine("    ExpiresActive On");
            sb.AppendLine("    ExpiresByType image/jpeg           \"access plus 1 month\"");
            sb.AppendLine("    ExpiresByType image/png            \"access plus 1 month\"");
            sb.AppendLine("    ExpiresByType image/gif            \"access plus 1 month\"");
            sb.AppendLine("    ExpiresByType image/webp           \"access plus 1 month\"");
            sb.AppendLine("    ExpiresByType image/svg+xml        \"access plus 1 month\"");
            sb.AppendLine("    ExpiresByType image/x-icon         \"access plus 1 year\"");
            sb.AppendLine("    ExpiresByType application/font-woff2 \"access plus 1 year\"");
            sb.AppendLine("    ExpiresByType text/css             \"access plus 1 week\"");
            sb.AppendLine("    ExpiresByType application/javascript \"access plus 1 week\"");
            sb.AppendLine("    ExpiresDefault                     \"access plus 2 days\"");
            sb.AppendLine("</IfModule>");
            sb.AppendLine();
        }

        // ── Virtual Hosts ──────────────────────────────────────────────────
        sb.AppendLine("# Virtual Hosts");
        sb.AppendLine($"IncludeOptional \"{P(configDir)}/vhosts/*.conf\"");

        // ── SSL Virtual Host ────────────────────────────────────────────────
        if (sslReady)
        {
            var certFile = P(_config.Apache.SslCertFile);
            var keyFile = P(_config.Apache.SslKeyFile);
            sb.AppendLine();
            sb.AppendLine("# HTTPS Virtual Host");
            sb.AppendLine($"<VirtualHost {VirtualHostAddress}:{_config.Apache.SslPort}>");
            sb.AppendLine($"    ServerName {_config.Apache.ServerName}");
            sb.AppendLine($"    DocumentRoot \"{P(wwwDir)}\"");
            sb.AppendLine($"    SSLEngine On");
            sb.AppendLine($"    SSLCertificateFile \"{certFile}\"");
            sb.AppendLine($"    SSLCertificateKeyFile \"{keyFile}\"");
            sb.AppendLine($"    SSLProtocol all -SSLv2 -SSLv3 -TLSv1 -TLSv1.1");
            sb.AppendLine($"    SSLCipherSuite ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384");
            sb.AppendLine($"    SSLHonorCipherOrder off");
            // Fix 4.4: HTTP/2 multiplexing — chỉ bật khi mod_http2.so có trên disk
            if (http2Available)
                sb.AppendLine($"    Protocols h2 http/1.1");
            sb.AppendLine();
            sb.AppendLine($"    RewriteEngine On");
            sb.AppendLine($"    RewriteRule \"^(/.+\\.php(/.*)?)$\" - [E=PHP_FCGI_SCRIPT:%{{DOCUMENT_ROOT}}$1,L]");
            sb.AppendLine();
            sb.AppendLine($"    <Directory \"{P(wwwDir)}\">");
            sb.AppendLine($"        Options {(isProd ? "-Indexes +FollowSymLinks" : "+Indexes +FollowSymLinks")}");
            sb.AppendLine($"        AllowOverride All");
            sb.AppendLine($"        Require all granted");
            sb.AppendLine($"        DirectoryIndex index.php index.html index.htm");
            sb.AppendLine($"    </Directory>");
            sb.AppendLine();
            sb.AppendLine("    # PHP via FastCGI (Windows-compatible)");
            sb.AppendLine("    <IfModule proxy_fcgi_module>");
            sb.AppendLine("        ProxyFCGIBackendType GENERIC");
            sb.AppendLine($"        ProxyPassMatch \"^/(.*\\.php(/.*)?)$\" \"fcgi://127.0.0.1:{_config.Php.FcgiPort}/$1\" {FcgiReuse}");
            sb.AppendLine("        ProxyFCGISetEnvIf \"%{ENV:PHP_FCGI_SCRIPT} != ''\" SCRIPT_FILENAME \"%{ENV:PHP_FCGI_SCRIPT}\"");
            sb.AppendLine("    </IfModule>");
            sb.AppendLine();
            sb.AppendLine($"    ErrorLog  \"{P(logsDir)}/ssl_error.log\"");
            sb.AppendLine($"    CustomLog \"{P(logsDir)}/ssl_access.log\" combined");
            sb.AppendLine("</VirtualHost>");
        }

        if (!string.IsNullOrWhiteSpace(_config.Apache.CustomDirectives))
        {
            sb.AppendLine();
            sb.AppendLine("# ── Custom Directives ──────────────────────────────────────────────────");
            sb.AppendLine(_config.Apache.CustomDirectives.TrimEnd());
            sb.AppendLine();
        }

        WriteIfChanged(outputPath, sb.ToString()); // Fix 2.4: chỉ ghi khi nội dung thực sự thay đổi
    }

    // ─── php.ini ─────────────────────────────────────────────────────────────

    public void WritePhpIni(string phpDir, string configDir, bool forceRegenerate = false)
    {
        var phpIniPath = Path.Combine(phpDir, "php.ini");
        var extDir = P(Path.Combine(phpDir, "ext"));
        if (File.Exists(phpIniPath) && !forceRegenerate)
        {
            var lines = File.ReadAllLines(phpIniPath);
            var headerLines = lines.Take(8).ToArray();
            bool isGenerated = headerLines.Contains(PhpIniGeneratedHeader, StringComparer.Ordinal) ||
                               headerLines.Contains(LegacyPhpIniGeneratedHeader, StringComparer.Ordinal);
            if (!isGenerated)
                return;

            // Generated php.ini files contain absolute Windows paths. Rebuild a current-schema
            // file after the portable server folder is copied or moved to another location.
            bool isCurrentSchema = headerLines.Contains(PhpIniSchemaMarker, StringComparer.Ordinal);
            if (isCurrentSchema && UsesExtensionDirectory(lines, extDir)) return;
        }

        bool isProd = _config.ServerMode == ServerMode.Production;
        var logsPath = P(Path.Combine(configDir, "logs"));
        var tmpPath = P(Path.GetTempPath().TrimEnd('\\', '/'));
        var caCertificatePath = P(Path.GetFullPath(Path.Combine(_rootDir, "ssl", "cacert.pem")));
        var caCertificateSettings = _config.Php.UseBundledCaCertificate
            ? $@"
[curl]
; Bundled CA store for HTTPS API requests
curl.cainfo = ""{caCertificatePath}""

[openssl]
openssl.cafile = ""{caCertificatePath}""
"
            : "";

        var configuredExtensions = _config.Php.EnabledExtensions ??
                                   PhpExtensionManager.RecommendedExtensions.ToList();
        var enabledExts = PhpExtensionManager.ResolveForRuntime(phpDir, configuredExtensions);
        var extensionLines = string.Join("\n", enabledExts.Select(extension => $"extension = {extension}"));
        var zendExtensionLine = _config.Php.EnableOpcache && PhpExtensionManager.HasOpcacheDll(phpDir)
            ? "zend_extension = opcache"
            : "";

        var content = $@"{PhpIniGeneratedHeader}
{PhpIniSchemaMarker}
; Mode: {_config.ServerMode}
; Edit freely. Hamster Server regenerates this file when PHP settings or its schema change.

[PHP]
; FastCGI (required on Windows)
cgi.force_redirect       = 0
fastcgi.impersonate      = 1
cgi.fix_pathinfo         = 1
; NOTE: cgi.rfc2616_headers removed — deprecated since PHP 8.3, removed in PHP 8.4+

; CRITICAL for FastCGI: buffer output so accidental prints don't corrupt HTTP headers.
; Without this, any PHP warning/notice output before headers causes ERR_INVALID_RESPONSE.
output_buffering         = 4096

; Extension directory (absolute path — required on Windows)
extension_dir = ""{extDir}""

; OPcache is configured separately because it is a Zend extension.
{zendExtensionLine}
; === Enabled extensions (managed via Hamster Server Settings → PHP → Extensions) ===
{extensionLines}

; Performance
max_execution_time       = {_config.Php.MaxExecutionTime}
max_input_time           = {_config.Php.MaxExecutionTime}
memory_limit             = {_config.Php.MemoryLimit}M
post_max_size            = 128M
upload_max_filesize      = 128M
max_input_vars           = 10000
realpath_cache_size      = 8192K
realpath_cache_ttl       = 600

; Error handling
; FASTCGI RULE: display_errors must ALWAYS be Off in FastCGI mode.
; Any PHP error/warning printed to stdout corrupts the FastCGI response headers (ERR_INVALID_RESPONSE).
; Errors go to error_log only — use config/logs/php_error.log to debug.
error_reporting          = {(isProd ? "E_ALL & ~E_DEPRECATED & ~E_STRICT" : "E_ALL")}
display_errors           = Off
display_startup_errors   = Off
log_errors               = On
error_log                = ""{logsPath}/php_error.log""
html_errors              = Off

; Misc
short_open_tag           = Off
default_charset          = ""UTF-8""
date.timezone            = ""{_config.Php.Timezone}""
file_uploads             = On
{caCertificateSettings}

[OPcache]
; OPcache dramatically reduces PHP startup time — essential for Laravel
opcache.enable                  = {(_config.Php.EnableOpcache ? 1 : 0)}
opcache.enable_cli              = 0
opcache.memory_consumption      = {_config.Php.OpcacheMemory}
opcache.interned_strings_buffer = {(isProd ? 64 : 32)}
opcache.max_accelerated_files   = {(isProd ? 65407 : 40000)}
opcache.max_wasted_percentage   = 5
opcache.revalidate_freq         = {(isProd ? 0 : 2)}
opcache.fast_shutdown           = 1
opcache.validate_timestamps     = {(isProd ? 0 : 1)}
opcache.save_comments           = 1

; JIT (PHP 8+) — function mode is stable on Windows; tracing mode can crash on mpm_winnt
; Switch to tracing only after confirming stability with your specific PHP version.
opcache.jit                     = function
opcache.jit_buffer_size         = {(isProd ? "128M" : "64M")}

[Session]
session.save_handler    = files
session.save_path       = ""{tmpPath}""
session.use_strict_mode = 1
session.cookie_httponly = 1
session.gc_maxlifetime  = 1440
";
        File.WriteAllText(phpIniPath, content);
    }

    private static bool UsesExtensionDirectory(IEnumerable<string> lines, string expectedPath)
    {
        foreach (var line in lines)
        {
            var trimmed = line.Trim();
            if (trimmed.StartsWith(';') || !trimmed.StartsWith("extension_dir", StringComparison.OrdinalIgnoreCase))
                continue;

            int separator = trimmed.IndexOf('=');
            if (separator < 0) return false;
            var value = trimmed[(separator + 1)..].Trim().Trim('"', '\'').Replace('\\', '/').TrimEnd('/');
            return value.Equals(expectedPath.TrimEnd('/'), StringComparison.OrdinalIgnoreCase);
        }

        return false;
    }

    // ─── VHost files ──────────────────────────────────────────────────────────

    public void WriteAllVHosts(string vhostDir)
    {
        ValidateConfiguration();
        Directory.CreateDirectory(vhostDir);
        var keep = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var wwwDir = Path.Combine(_rootDir, "www");

        // 00-default.conf — main port only (single port per VirtualHost on Windows)
        var defaultFile = Path.Combine(vhostDir, "00-default.conf");
        WriteIfChanged(defaultFile, BuildDefaultVHost(wwwDir));
        keep.Add(defaultFile);

        // 20-port-XXXX.conf — one file per extra port, each a separate VirtualHost.
        // Skip ports that already have a custom VHost assigned — the custom VHost
        // becomes the default (first) VirtualHost for that port automatically.
        var customVHostPorts = new HashSet<int>(
            _config.VHosts
                .Where(v => v.Enabled)
                .Select(v => v.Port > 0 ? v.Port : _config.Apache.Port));

        foreach (var ep in _config.Apache.ExtraPorts.Where(p => p.Enabled))
        {
            if (customVHostPorts.Contains(ep.Port)) continue;

            var suffix = ep.IsSsl ? $"ssl-{ep.Port}" : ep.Port.ToString();
            var file = Path.Combine(vhostDir, $"20-port-{suffix}.conf");
            var content = ep.IsSsl
                ? BuildExtraSslPortVHost(ep.Port, wwwDir)
                : BuildExtraPortVHost(ep.Port, wwwDir);
            WriteIfChanged(file, content);
            keep.Add(file);
        }

        // 10-XXXX.conf — custom VHosts (on main port)
        foreach (var v in _config.VHosts.Where(v => v.Enabled))
        {
            var file = Path.Combine(vhostDir, $"10-{SafeName(v.ServerName)}.conf");
            WriteIfChanged(file, BuildVHost(v));
            keep.Add(file);
        }

        // Remove stale .conf files that are no longer needed.
        // A single locked file (open in an editor) must not abort the whole Apache start —
        // a leftover vhost is a lesser problem than not starting at all.
        foreach (var f in Directory.GetFiles(vhostDir, "*.conf"))
        {
            if (keep.Contains(f)) continue;
            try { File.Delete(f); }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
        }
    }

    private static void WriteIfChanged(string path, string content)
    {
        if (File.Exists(path))
        {
            // Normalize line endings before comparing to avoid CRLF vs LF false mismatches
            var existing = File.ReadAllText(path).ReplaceLineEndings("\n");
            if (existing == content.ReplaceLineEndings("\n")) return;
        }
        File.WriteAllText(path, content);
    }

    private static string SafeName(string serverName)
    {
        var slug = new string(serverName.ToLowerInvariant()
            .Select(ch => char.IsLetterOrDigit(ch) || ch is '-' or '_' ? ch : '_')
            .ToArray()).Trim('_');
        if (slug.Length == 0) slug = "vhost";
        if (slug.Length > 48) slug = slug[..48];
        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(serverName)))[..10]
            .ToLowerInvariant();
        return $"{slug}-{hash}";
    }

    private void ValidateConfiguration()
    {
        if (!IsValidServerName(_config.Apache.ServerName))
            throw new InvalidDataException($"Invalid Apache server name: {_config.Apache.ServerName}");

        var duplicate = _config.VHosts
            .Where(vhost => vhost.Enabled)
            .GroupBy(vhost => vhost.ServerName, StringComparer.OrdinalIgnoreCase)
            .FirstOrDefault(group => group.Count() > 1);
        if (duplicate is not null)
            throw new InvalidDataException($"Duplicate virtual host name: {duplicate.Key}");

        var configuredPorts = new HashSet<int> { _config.Apache.Port };
        if (_config.Apache.EnableSsl) configuredPorts.Add(_config.Apache.SslPort);
        foreach (var extraPort in _config.Apache.ExtraPorts.Where(port => port.Enabled))
            configuredPorts.Add(extraPort.Port);

        foreach (var vhost in _config.VHosts.Where(vhost => vhost.Enabled))
        {
            if (!IsValidServerName(vhost.ServerName))
                throw new InvalidDataException($"Invalid virtual host name: {vhost.ServerName}");
            if (!AreValidServerAliases(vhost.ServerAlias))
                throw new InvalidDataException($"Invalid aliases for virtual host: {vhost.ServerName}");
            if (vhost.Port > 0 && !configuredPorts.Contains(vhost.Port))
                throw new InvalidDataException($"Virtual host {vhost.ServerName} uses an inactive port: {vhost.Port}");
            if (vhost.DocumentRoot.IndexOfAny(['\r', '\n', '"']) >= 0)
                throw new InvalidDataException($"Invalid document root for virtual host: {vhost.ServerName}");

            var profile = FrameworkProfiles.Get(vhost.Framework);
            if (profile.IsReverseProxy &&
                (!Uri.TryCreate(vhost.DocumentRoot, UriKind.Absolute, out var proxyUri) ||
                 proxyUri.Scheme is not ("http" or "https")))
            {
                throw new InvalidDataException($"Invalid proxy URL for {vhost.ServerName}: {vhost.DocumentRoot}");
            }
        }
    }

