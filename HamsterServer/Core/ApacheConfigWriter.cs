    private string BuildExtraSslPortVHost(int port, string wwwDir)
    {
        bool isProd = _config.ServerMode == ServerMode.Production;
        var certFile = P(_config.Apache.SslCertFile);
        var keyFile = P(_config.Apache.SslKeyFile);
        var lPath = P(Path.Combine(_rootDir, "config", "logs"));
        var dPath = P(wwwDir);
        int fcgiPort = _config.Php.FcgiPort;

        var sb = new StringBuilder();
        sb.AppendLine($"# Extra SSL port {port}");
        sb.AppendLine($"<VirtualHost {VirtualHostAddress}:{port}>");
        sb.AppendLine($"    ServerName {_config.Apache.ServerName}");
        sb.AppendLine($"    DocumentRoot \"{dPath}\"");
        sb.AppendLine($"    SSLEngine On");
        sb.AppendLine($"    SSLCertificateFile \"{certFile}\"");
        sb.AppendLine($"    SSLCertificateKeyFile \"{keyFile}\"");
        sb.AppendLine($"    SSLProtocol all -SSLv2 -SSLv3 -TLSv1 -TLSv1.1");
        sb.AppendLine($"    SSLHonorCipherOrder off");
        sb.AppendLine();
        sb.AppendLine("    # Capture real filesystem path before mod_proxy_fcgi takes over (works with spaces).");
        sb.AppendLine("    RewriteEngine On");
        sb.AppendLine("    RewriteRule \"^(/.+\\.php)(/.*)?$\" - [E=PHP_FCGI_SCRIPT:%{DOCUMENT_ROOT}$1,L]");
        sb.AppendLine();
        sb.AppendLine($"    <Directory \"{dPath}\">");
        sb.AppendLine($"        Options {(isProd ? "-Indexes +FollowSymLinks" : "+Indexes +FollowSymLinks")}");
        sb.AppendLine("        AllowOverride All");
        sb.AppendLine("        Require all granted");
        sb.AppendLine("        DirectoryIndex index.php index.html index.htm");
        sb.AppendLine("    </Directory>");
        sb.AppendLine();
        sb.AppendLine("    # PHP via FastCGI (Windows-compatible)");
        sb.AppendLine("    <IfModule proxy_fcgi_module>");
        sb.AppendLine("        ProxyFCGIBackendType GENERIC");
        sb.AppendLine($"        ProxyPassMatch \"^/(.*\\.php(/.*)?)$\" \"fcgi://127.0.0.1:{fcgiPort}/$1\" {FcgiReuse}");
        sb.AppendLine("        ProxyFCGISetEnvIf \"%{ENV:PHP_FCGI_SCRIPT} != ''\" SCRIPT_FILENAME \"%{ENV:PHP_FCGI_SCRIPT}\"");
        sb.AppendLine("    </IfModule>");
        sb.AppendLine();
        sb.AppendLine($"    ErrorLog \"{lPath}/port_{port}_error.log\"");
        sb.AppendLine($"    CustomLog \"{lPath}/port_{port}_access.log\" combined");
        sb.AppendLine("</VirtualHost>");
        return sb.ToString();
    }

    private string BuildVHost(VHostEntry vhost)
    {
        bool isProd = _config.ServerMode == ServerMode.Production;
        var lPath = P(Path.Combine(_rootDir, "config", "logs"));
        var safe = SafeName(vhost.ServerName);
        int port = vhost.Port > 0 ? vhost.Port : _config.Apache.Port;
        var alias = string.IsNullOrWhiteSpace(vhost.ServerAlias)
                       ? "" : $"    ServerAlias {vhost.ServerAlias}\n";

        var profile = FrameworkProfiles.Get(vhost.Framework);
        if (profile.IsReverseProxy)
            return BuildHyperfVHost(vhost, port, alias, lPath, safe);

        // ── PHP framework VHost ───────────────────────────────────────────────
        var configuredRoot = string.IsNullOrWhiteSpace(vhost.DocumentRoot)
            ? Path.Combine(_rootDir, "www", vhost.ServerName)
            : vhost.DocumentRoot;
        var absoluteRoot = Path.IsPathRooted(configuredRoot)
            ? configuredRoot
            : Path.Combine(_rootDir, "www", configuredRoot);
        var docRoot = FrameworkProfiles.ResolveDocumentRoot(absoluteRoot, vhost.Framework);

        var dPath = P(docRoot);
        return BuildPhpFrameworkVHost(profile, port, vhost.ServerName, alias,
                                      dPath, isProd, lPath, safe);
    }

    private string BuildHyperfVHost(
        VHostEntry vhost, int port, string alias, string lPath, string safe)
    {
        var proxyTarget = string.IsNullOrWhiteSpace(vhost.DocumentRoot)
            ? "http://127.0.0.1:9501"
            : vhost.DocumentRoot.TrimEnd('/');

        // Extract host:port from proxy URL for WebSocket rewrite
        var wsTarget = proxyTarget.Replace("http://", "ws://").Replace("https://", "wss://");

        return $@"# VHost: {vhost.ServerName} (Hyperf/Swoole Proxy) — Auto-generated by Hamster Server
<VirtualHost {VirtualHostAddress}:{port}>
    ServerName {vhost.ServerName}
{alias}
    ProxyPreserveHost On
    ProxyRequests Off

    # HTTP proxy → Swoole
    ProxyPass / {proxyTarget}/
    ProxyPassReverse / {proxyTarget}/

    # WebSocket proxy
    RewriteEngine On
    RewriteCond %{{HTTP:Upgrade}} websocket [NC]
    RewriteCond %{{HTTP:Connection}} upgrade [NC]
    RewriteRule ^/?(.*)$ {wsTarget}/$1 [P,L]

    ErrorLog  ""{lPath}/{safe}_error.log""
    CustomLog ""{lPath}/{safe}_access.log"" combined
</VirtualHost>
";
    }

    private string BuildPhpFrameworkVHost(
        FrameworkProfile profile, int port,
        string serverName, string alias,
        string dPath, bool isProd, string lPath, string safe)
    {
        var indexDirective = profile.Preset switch
        {
            FrameworkPreset.CakePHP => "index.php index.html",
            _ => "index.php index.html index.htm"
        };

        var dirOptions = isProd
            ? "-Indexes +FollowSymLinks -MultiViews"
            : "+Indexes +FollowSymLinks -MultiViews";

        // Front-controller fallback rewrite inside <Directory> (belt & suspenders with .htaccess)
        var rewriteBlock = profile.UsesFrontController
            ? $@"
        RewriteEngine On
        RewriteBase /
        RewriteCond %{{REQUEST_FILENAME}} !-f
        RewriteCond %{{REQUEST_FILENAME}} !-d
        RewriteRule ^ index.php [QSA,L,E=PHP_FCGI_SCRIPT:%{{DOCUMENT_ROOT}}/index.php]"
            : "";

        // Security rules for sensitive files
        var securityBlock = !string.IsNullOrWhiteSpace(profile.SensitiveFilesPattern)
            ? $@"
    # Block sensitive files
    <FilesMatch ""{profile.SensitiveFilesPattern}"">
        Require all denied
    </FilesMatch>
    <DirectoryMatch ""/\."">
        Require all denied
    </DirectoryMatch>
"
            : "";

        var extensionComment = profile.RequiredExtensions.Length == 0
            ? ""
            : $"# Expected PHP extensions: {string.Join(", ", profile.RequiredExtensions)}\n";

        int fcgiPort = _config.Php.FcgiPort;

        return $@"# VHost: {serverName} ({profile.DisplayName}) — Auto-generated by Hamster Server
{extensionComment}<VirtualHost {VirtualHostAddress}:{port}>
    ServerName {serverName}
{alias}    DocumentRoot ""{dPath}""

    # Capture real filesystem path before mod_proxy_fcgi takes over (works with spaces).
    RewriteEngine On
    RewriteRule ""^(/.+\.php)(/.*)?$"" - [E=PHP_FCGI_SCRIPT:%{{DOCUMENT_ROOT}}$1,L]
    SetEnvIf Authorization ""(.+)"" HTTP_AUTHORIZATION=$1
{securityBlock}
    <Directory ""{dPath}"">
        Options {dirOptions}
        AllowOverride All
        Require all granted
        DirectoryIndex {indexDirective}{rewriteBlock}
    </Directory>

    # PHP via FastCGI (Windows-compatible)
    <IfModule proxy_fcgi_module>
        ProxyFCGIBackendType GENERIC
        ProxyPassMatch ""^/(.*\.php(/.*)?)$"" ""fcgi://127.0.0.1:{fcgiPort}/$1"" {FcgiReuse}
        ProxyFCGISetEnvIf ""%{{ENV:PHP_FCGI_SCRIPT}} != ''"" SCRIPT_FILENAME ""%{{ENV:PHP_FCGI_SCRIPT}}""
    </IfModule>

    ErrorLog  ""{lPath}/{safe}_error.log""
    CustomLog ""{lPath}/{safe}_access.log"" combined
</VirtualHost>
";
    }

    private string BuildPortVHost(
        int port, string serverName, string serverAlias,
        string docRoot, bool isProd,
        string errorLog, string accessLog, string header,
        int fcgiPort)
    {
        var alias = string.IsNullOrWhiteSpace(serverAlias)
            ? "" : $"    ServerAlias {serverAlias}\n";

        return $@"# {header} — Auto-generated by Hamster Server
<VirtualHost {VirtualHostAddress}:{port}>
    ServerName {serverName}
{alias}    DocumentRoot ""{docRoot}""

    # Capture real filesystem path before mod_proxy_fcgi takes over (works with spaces).
    RewriteEngine On
    RewriteRule ""^(/.+\.php)(/.*)?$"" - [E=PHP_FCGI_SCRIPT:%{{DOCUMENT_ROOT}}$1,L]

    <Directory ""{docRoot}"">
        Options {(isProd ? "-Indexes +FollowSymLinks" : "+Indexes +FollowSymLinks")}
        AllowOverride All
        Require all granted
        DirectoryIndex index.php index.html index.htm
    </Directory>

    # PHP via FastCGI (Windows-compatible)
    <IfModule proxy_fcgi_module>
        ProxyFCGIBackendType GENERIC
        ProxyPassMatch ""^/(.*\.php(/.*)?)$"" ""fcgi://127.0.0.1:{fcgiPort}/$1"" {FcgiReuse}
        ProxyFCGISetEnvIf ""%{{ENV:PHP_FCGI_SCRIPT}} != ''"" SCRIPT_FILENAME ""%{{ENV:PHP_FCGI_SCRIPT}}""
    </IfModule>

    ErrorLog  ""{errorLog}""
    CustomLog ""{accessLog}"" combined
</VirtualHost>
";
    }
