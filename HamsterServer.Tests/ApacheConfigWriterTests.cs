using HamsterServer.Core;
using HamsterServer.Models;

namespace HamsterServer.Tests;

[TestClass]
public sealed class ApacheConfigWriterTests
{
    [TestMethod]
    public void WritePhpIni_SynchronizesAvailableExtensionsAndLoadsOpcacheAsZendExtension()
    {
        using var root = new TestDirectory();
        var phpDir = Path.Combine(root.Path, "php", "8.4.24");
        var extDir = Path.Combine(phpDir, "ext");
        Directory.CreateDirectory(extDir);
        File.WriteAllBytes(Path.Combine(extDir, "php_curl.dll"), []);
        File.WriteAllBytes(Path.Combine(extDir, "php_opcache.dll"), []);
        var config = new AppConfig();
        config.Php.EnabledExtensions = ["curl", "imap", "opcache"];

        new ApacheConfigWriter(root.Path, config).WritePhpIni(
            phpDir, Path.Combine(root.Path, "config"));

        var text = File.ReadAllText(Path.Combine(phpDir, "php.ini"));
        var lines = text.ReplaceLineEndings("\n").Split('\n');
        StringAssert.Contains(text, "zend_extension = opcache");
        StringAssert.Contains(text, "extension = curl");
        Assert.IsFalse(lines.Contains("extension = imap", StringComparer.Ordinal));
        Assert.IsFalse(lines.Contains("extension = opcache", StringComparer.Ordinal));
    }

    [TestMethod]
    public void WritePhpIni_UpgradesGeneratedFileFromPreviousSchema()
    {
        using var root = new TestDirectory();
        var phpDir = Path.Combine(root.Path, "php", "8.5.9");
        Directory.CreateDirectory(phpDir);
        var phpIni = Path.Combine(phpDir, "php.ini");
        File.WriteAllText(phpIni, "; PHP FastCGI Configuration — Generated by Hamster Server\n; old schema");

        new ApacheConfigWriter(root.Path, new AppConfig()).WritePhpIni(
            phpDir, Path.Combine(root.Path, "config"));

        var text = File.ReadAllText(phpIni);
        StringAssert.Contains(text, "; Hamster Server php.ini schema: 2");
        Assert.IsFalse(text.Contains("old schema", StringComparison.Ordinal));
    }

