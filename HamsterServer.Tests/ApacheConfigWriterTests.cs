    [TestMethod]
    public void WritePhpIni_UsesBundledCaCertificateByDefault()
    {
        using var root = new TestDirectory();
        var phpDir = Path.Combine(root.Path, "php", "8.5.9");
        var configDir = Path.Combine(root.Path, "config");
        Directory.CreateDirectory(phpDir);

        new ApacheConfigWriter(root.Path, new AppConfig()).WritePhpIni(phpDir, configDir);

        var text = File.ReadAllText(Path.Combine(phpDir, "php.ini"));
        var expectedPath = Path.Combine(root.Path, "ssl", "cacert.pem").Replace('\\', '/');
        StringAssert.Contains(text, "[curl]");
        StringAssert.Contains(text, $"curl.cainfo = \"{expectedPath}\"");
        StringAssert.Contains(text, "[openssl]");
        StringAssert.Contains(text, $"openssl.cafile = \"{expectedPath}\"");
    }

    [TestMethod]
    public void WritePhpIni_OmitsBundledCaCertificateWhenDisabled()
    {
        using var root = new TestDirectory();
        var phpDir = Path.Combine(root.Path, "php", "8.5.9");
        Directory.CreateDirectory(phpDir);
        var config = new AppConfig();
        config.Php.UseBundledCaCertificate = false;

        new ApacheConfigWriter(root.Path, config).WritePhpIni(
            phpDir, Path.Combine(root.Path, "config"));

        var text = File.ReadAllText(Path.Combine(phpDir, "php.ini"));
        Assert.IsFalse(text.Contains("curl.cainfo", StringComparison.Ordinal));
        Assert.IsFalse(text.Contains("openssl.cafile", StringComparison.Ordinal));
    }

    [TestMethod]
    public void WriteHttpdConf_BindsOnlyToLoopbackByDefault()
    {
        using var root = new TestDirectory();
        var apacheDir = Path.Combine(root.Path, "apache", "Apache24");
        var configDir = Path.Combine(root.Path, "config");
        var wwwDir = Path.Combine(root.Path, "www");
        Directory.CreateDirectory(apacheDir);
        var config = new AppConfig();
        config.Apache.ExtraPorts.Add(new PortEntry { Port = 8080 });

        var output = Path.Combine(configDir, "httpd.conf");
        new ApacheConfigWriter(root.Path, config).WriteHttpdConf(output, apacheDir, wwwDir, configDir);
        var text = File.ReadAllText(output);

        StringAssert.Contains(text, "Listen 127.0.0.1:80");
        StringAssert.Contains(text, "Listen 127.0.0.1:8080");
        Assert.IsFalse(text.ReplaceLineEndings("\n").Split('\n').Contains("Listen 80"));
    }

    [TestMethod]
    public void WriteHttpdConf_AllowsAllInterfacesOnlyWhenExplicitlyEnabled()
    {
        using var root = new TestDirectory();
        var apacheDir = Path.Combine(root.Path, "apache", "Apache24");
        var configDir = Path.Combine(root.Path, "config");
        Directory.CreateDirectory(apacheDir);
        var config = new AppConfig();
        config.Apache.AllowLanAccess = true;

        var output = Path.Combine(configDir, "httpd.conf");
        new ApacheConfigWriter(root.Path, config).WriteHttpdConf(
            output, apacheDir, Path.Combine(root.Path, "www"), configDir);

        StringAssert.Contains(File.ReadAllText(output), "Listen 80");
    }

    [TestMethod]
    public void WriteAllVHosts_UsesCollisionResistantFileNames()
    {
        using var root = new TestDirectory();
        var config = new AppConfig
        {
            VHosts =
            [
                new VHostEntry { ServerName = "a.b", DocumentRoot = root.Path },
                new VHostEntry { ServerName = "a-b", DocumentRoot = root.Path }
            ]
        };
        var vhostDir = Path.Combine(root.Path, "config", "vhosts");

        new ApacheConfigWriter(root.Path, config).WriteAllVHosts(vhostDir);

        var customFiles = Directory.GetFiles(vhostDir, "10-*.conf");
        Assert.AreEqual(2, customFiles.Length);
        var combined = string.Join('\n', customFiles.Select(File.ReadAllText));
        StringAssert.Contains(combined, "ServerName a.b");
        StringAssert.Contains(combined, "ServerName a-b");
    }

    [TestMethod]
    public void WriteAllVHosts_AppliesLaravelProfile()
    {
        using var root = new TestDirectory();
        var projectRoot = Path.Combine(root.Path, "laravel-app");
        var publicDir = Path.Combine(projectRoot, "public");
        Directory.CreateDirectory(publicDir);
        File.WriteAllText(Path.Combine(publicDir, "index.php"), "<?php");
        var config = new AppConfig
        {
            VHosts =
            [
                new VHostEntry
                {
                    ServerName = "laravel.test",
                    DocumentRoot = projectRoot,
                    Framework = FrameworkPreset.Laravel
                }
            ]
        };
        var vhostDir = Path.Combine(root.Path, "config", "vhosts");

        new ApacheConfigWriter(root.Path, config).WriteAllVHosts(vhostDir);

        var text = File.ReadAllText(Directory.GetFiles(vhostDir, "10-*.conf").Single());
        StringAssert.Contains(text, $"DocumentRoot \"{publicDir.Replace('\\', '/')}\"");
        StringAssert.Contains(text, "Options +Indexes +FollowSymLinks -MultiViews");
        StringAssert.Contains(text, "RewriteRule ^ index.php");
        StringAssert.Contains(text, "HTTP_AUTHORIZATION");
        StringAssert.Contains(text, "Expected PHP extensions:");
    }

    [TestMethod]
    public void WriteAllVHosts_RejectsDuplicateEnabledServerNames()
    {
        using var root = new TestDirectory();
        var config = new AppConfig
        {
            VHosts =
            [
                new VHostEntry { ServerName = "app.test", DocumentRoot = root.Path },
                new VHostEntry { ServerName = "APP.TEST", DocumentRoot = root.Path }
            ]
        };

        var error = Assert.ThrowsExactly<InvalidDataException>(() =>
            new ApacheConfigWriter(root.Path, config)
                .WriteAllVHosts(Path.Combine(root.Path, "config", "vhosts")));

        StringAssert.Contains(error.Message, "Duplicate virtual host name");
    }

    [DataTestMethod]
    [DataRow("localhost", true)]
    [DataRow("app.test", true)]
    [DataRow("*.app.test", true)]
    [DataRow("bad host", false)]
    [DataRow("", false)]
    public void IsValidServerName_ValidatesDnsTokens(string value, bool expected) =>
        Assert.AreEqual(expected, ApacheConfigWriter.IsValidServerName(value));
}
